#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""许可守护打包脚本 —— 把过期时间/授权时长/巡检参数烧进 _launcher.so。

用法:
    python build_license.py --days 90
    python build_license.py --days 30 --check-interval 30 --tolerance 5 --output-dir ./out

流程:
    1) 计算 EXPIRY_TIMESTAMP = 当前时间戳 + 授权天数
    2) 生成 license_config.h:  烧入参数
    3) 生成 app_payload.h:     app_main.py 异或混淆后的字节数组 (运行时逻辑入 .so)
    4) 用 gcc 编译 launcher.c -> _launcher<EXT_SUFFIX>  (-s 去符号表)
    5) 默认删除中间源码, 只留 .so

产物:
    <output-dir>/_launcher<EXT_SUFFIX>     受保护模块 (含守卫 + 内嵌业务)
    (--keep-src 时额外保留 license_config.h / app_payload.h / launcher.c)
"""
import argparse
import os
import shutil
import subprocess
import sys
import sysconfig
import time

HERE = os.path.dirname(os.path.abspath(__file__))
C_SRC = os.path.join(HERE, 'launcher.c')
APP_SRC = os.path.join(HERE, 'app_main.py')

# 内嵌业务逻辑的异或密钥 (防 strings/暴力 grep, 非加密强度)
PAYLOAD_KEY = bytes([0x5a, 0x8b, 0x3c, 0xd1, 0x7f, 0x2e, 0x96, 0x44])

CONFIG_H = """\
/* auto-generated by build_license.py, do not edit */
#ifndef LICENSE_CONFIG_H
#define LICENSE_CONFIG_H
#define LICENSE_EXPIRY_TIMESTAMP         {expiry}LL
#define LICENSE_MAX_INTERVAL_SECONDS     {max_interval}LL
#define LICENSE_CHECK_INTERVAL_SECONDS   {check_interval}LL
#define LICENSE_CHECK_TOLERANCE_SECONDS  {tolerance}LL
#endif /* LICENSE_CONFIG_H */
"""


def _bytes_to_c_array(name, data):
    rows = []
    for i in range(0, len(data), 16):
        rows.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    return 'static const unsigned char %s[] = {\n%s\n};' % (name, '\n'.join(rows))


def make_payload_header(raw: bytes) -> str:
    ob = bytes((b ^ PAYLOAD_KEY[i % len(PAYLOAD_KEY)]) for i, b in enumerate(raw))
    return ('/* auto-generated by build_license.py, do not edit */\n'
            '#ifndef APP_PAYLOAD_H\n'
            '#define APP_PAYLOAD_H\n'
            + _bytes_to_c_array('APP_PAYLOAD_KEY', PAYLOAD_KEY) + '\n'
            + _bytes_to_c_array('APP_PAYLOAD', ob) + '\n'
            '#endif /* APP_PAYLOAD_H */\n')


def _ts(v):
    return time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(v))


def main():
    ap = argparse.ArgumentParser(description='编译 LazyLLM 许可守护 _launcher.so')
    ap.add_argument('--days', type=float, default=90.0, help='授权天数(从打包时刻起算), 默认 90')
    ap.add_argument('--check-interval', type=int, default=30,
                    help='后台巡检间隔(秒), 默认 30')
    ap.add_argument('--tolerance', type=int, default=5,
                    help='允许的时钟浮动(秒), 默认 5; 须小于 check-interval')
    ap.add_argument('--output-dir', default=HERE, help='.so 输出目录, 默认脚本所在目录')
    ap.add_argument('--keep-src', action='store_true',
                    help='保留生成的 launcher.c / license_config.h (调试用)')
    ap.add_argument('--cc', default=os.environ.get('CC', 'gcc'), help='C 编译器, 默认 gcc')
    ap.add_argument('--include', default=None,
                    help='Python 头文件目录 (默认取 sysconfig), 跨架构编译时指定')
    ap.add_argument('--ext-suffix', default=None,
                    help='扩展后缀, 如 .cpython-310-aarch64-linux-gnu.so (默认取 sysconfig)')
    ap.add_argument('--app-file', default=APP_SRC,
                    help='运行时业务源码 (默认 app_main.py), 会烧入 .so')
    args = ap.parse_args()

    if args.days <= 0:
        sys.exit('[build_license] --days 必须 > 0')
    if args.check_interval <= 0:
        sys.exit('[build_license] --check-interval 必须 > 0')
    if not (0 < args.tolerance < args.check_interval):
        sys.exit('[build_license] --tolerance 必须满足 0 < tolerance < check-interval')

    now = int(time.time())
    max_interval = int(args.days * 86400)
    # max_interval = int(args.days * 60)
    expiry = now + max_interval

    out_dir = os.path.abspath(args.output_dir)
    os.makedirs(out_dir, exist_ok=True)

    # 1) 生成烧入参数的 header (放在输出目录, 编译时随 launcher.c 一起带入)
    cfg_path = os.path.join(out_dir, 'license_config.h')
    with open(cfg_path, 'w', encoding='ascii') as f:
        f.write(CONFIG_H.format(
            expiry=expiry,
            max_interval=max_interval,
            check_interval=args.check_interval,
            tolerance=args.tolerance,
        ))

    # 1b) 生成内嵌业务逻辑的 header (XOR 混淆 -> 进 .so)
    if not os.path.exists(args.app_file):
        sys.exit(f'[build_license] 找不到业务源码 {args.app_file!r}')
    with open(args.app_file, 'rb') as f:
        raw = f.read()
    payload_path = os.path.join(out_dir, 'app_payload.h')
    with open(payload_path, 'w', encoding='ascii') as f:
        f.write(make_payload_header(raw))

    # 2) 复制 C 源码到输出目录, 使其 #include "license_config.h" 命中生成的 header
    src_path = os.path.join(out_dir, 'launcher.c')
    if os.path.abspath(src_path) != os.path.abspath(C_SRC):
        shutil.copyfile(C_SRC, src_path)

    # 3) 编译 (module 不链接 libpython, 运行时符号由解释器提供)
    ext_suffix = args.ext_suffix or (sysconfig.get_config_var('EXT_SUFFIX') or '.so')
    inc_dir = args.include or sysconfig.get_paths()['include']
    so_path = os.path.join(out_dir, '_launcher' + ext_suffix)

    cmd = [
        args.cc, '-O2', '-shared', '-fPIC', '-s',
        '-I', inc_dir,
        '-I', out_dir,
        '-o', so_path,
        src_path,
    ]
    print('[build_license] $', ' '.join(cmd))
    try:
        subprocess.check_call(cmd)
    except FileNotFoundError:
        sys.exit(f'[build_license] 找不到编译器 {args.cc!r}, 请安装 gcc (或指定 --cc)')
    except subprocess.CalledProcessError as e:
        sys.exit(f'[build_license] 编译失败 (exit {e.returncode})')

    if not args.keep_src:
        if os.path.abspath(src_path) != os.path.abspath(C_SRC):
            os.remove(src_path)
        os.remove(cfg_path)
        os.remove(payload_path)

    print(f'[build_license] expiry    = {expiry}  ({_ts(expiry)})')
    print(f'[build_license] 授权天数  = {args.days} 天  (max_interval={max_interval}s)')
    print(f'[build_license] 巡检间隔  = {args.check_interval}s  (容差 ±{args.tolerance}s)')
    print(f'[build_license] 内嵌业务  = {args.app_file}  ({len(raw)} bytes -> app_payload.h)')
    print(f'[build_license] 输出      = {so_path}')


if __name__ == '__main__':
    main()